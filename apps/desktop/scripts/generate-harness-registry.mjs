#!/usr/bin/env node
/**
 * Deterministic registry aggregation. The public generate:registry command
 * builds packages first; this script only validates and consumes artifacts.
 * ./manifest is pure data, and ./main + ./renderer have stable default exports.
 * Never execute a process implementation or infer exports from .d.ts text here.
 */
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, isAbsolute, join, relative, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const desktopRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(join(desktopRoot, 'package.json'))
const desktopPackage = JSON.parse(readFileSync(join(desktopRoot, 'package.json'), 'utf8'))
const packagePattern = /^@openagent\/harness-([a-z][a-z0-9-]*)$/
const harnessNames = Object.keys(desktopPackage.dependencies ?? {})
  .filter((name) => name.startsWith('@openagent/harness-'))

for (const name of Object.keys(desktopPackage.devDependencies ?? {})) {
  if (name.startsWith('@openagent/harness-') && !harnessNames.includes(name)) {
    throw new Error(`${name}: Harness 必须声明在 dependencies，不能仅在 devDependencies`)
  }
}
if (harnessNames.length === 0) throw new Error('未发现任何 @openagent/harness-* 插件包')

function artifact(packageRoot, packageName, value) {
  if (typeof value !== 'string' || !value.startsWith('./') || value.includes('*')) {
    throw new Error(`${packageName}: 模块入口必须为明确的包内相对文件路径`)
  }
  const path = resolve(packageRoot, value)
  const local = relative(packageRoot, path)
  if (isAbsolute(local) || local === '..' || local.startsWith('../') || local.startsWith('..\\')) {
    throw new Error(`${packageName}: 模块入口不得越出包目录`)
  }
  if (!existsSync(path) || !statSync(path).isFile()) {
    throw new Error(`${packageName}: 缺少构建产物 ${path}；请运行 pnpm generate:registry`)
  }
  return path
}

function validThreadCapabilities(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value) &&
    typeof value.instructions === 'boolean' &&
    typeof value.threadContext === 'boolean' &&
    typeof value.sendContext === 'boolean' &&
    Array.isArray(value.toolModes) &&
    value.toolModes.every((mode) => mode === 'extend' || mode === 'exclusive') &&
    new Set(value.toolModes).size === value.toolModes.length
}

const entries = []
const ids = new Set()
for (const name of harnessNames) {
  const match = packagePattern.exec(name)
  if (!match) throw new Error(`${name}: 无效的 Harness 包名`)
  const packageJsonPath = require.resolve(`${name}/package.json`)
  const packageRoot = dirname(packageJsonPath)
  const metadata = JSON.parse(readFileSync(packageJsonPath, 'utf8'))
  if (metadata.name !== name) throw new Error(`${name}: package.json.name 不匹配`)
  const paths = {}
  for (const subpath of ['./manifest', './main', './renderer']) {
    const entry = metadata.exports?.[subpath]
    if (!entry || typeof entry !== 'object' || !entry.default || !entry.types) {
      throw new Error(`${name}: ${subpath} 必须声明 types 与 default 入口`)
    }
    paths[subpath] = artifact(packageRoot, name, entry.default)
    artifact(packageRoot, name, entry.types)
  }
  const { default: descriptor } = await import(pathToFileURL(paths['./manifest']).href)
  if (!descriptor || descriptor.id !== match[1] ||
      typeof descriptor.displayName !== 'string' || !descriptor.displayName.trim() ||
      !validThreadCapabilities(descriptor.threadCapabilities)) {
    throw new Error(`${name}: ./manifest 必须默认导出有效 descriptor，id 必须匹配包名`)
  }
  if (ids.has(descriptor.id)) throw new Error(`Harness id 重复: ${descriptor.id}`)
  ids.add(descriptor.id)
  entries.push({ name, descriptor })
}

const header = `/**
 * Code-generated by scripts/generate-harness-registry.mjs — do not edit.
 * Re-run \`pnpm generate:registry\` (builds workspace packages before aggregation).
 */\n`
const descriptors = Object.fromEntries(entries.map(({ descriptor }) => [descriptor.id, {
  id: descriptor.id,
  displayName: descriptor.displayName,
  threadCapabilities: descriptor.threadCapabilities
}]))
const shared = `${header}
import type { HarnessPluginDescriptor } from '@openagent/contracts'
export type { HarnessPluginDescriptor } from '@openagent/contracts'

export const harnessDescriptors = ${JSON.stringify(descriptors, null, 2)} as const satisfies Record<string, HarnessPluginDescriptor<string>>

export type HarnessId = keyof typeof harnessDescriptors
export const HARNESS_IDS = Object.keys(harnessDescriptors) as HarnessId[]

export function isHarnessId(value: unknown): value is HarnessId {
  return typeof value === 'string' && Object.hasOwn(harnessDescriptors, value)
}

/** Unregistered ids degrade to their raw id. */
export function harnessDisplayName(harnessId: string): string {
  return isHarnessId(harnessId) ? harnessDescriptors[harnessId].displayName : harnessId
}
`

function processRegistry(process) {
  const label = process === 'main' ? 'Main' : 'Renderer'
  const type = `ErasedHarness${label}PluginModule`
  const contract = process === 'main' ? '@openagent/contracts' : '@openagent/contracts/renderer'
  const lines = [header,
    `import type { ${type} } from '${contract}'`,
    `import { harnessDescriptors } from './harness-registry'`,
    ...entries.map(({ name }, i) => `import plugin${i} from '${name}/${process}'`),
    '',
    `const entries: readonly (readonly [keyof typeof harnessDescriptors, ${type}])[] = [`,
    ...entries.map(({ descriptor }, i) => `  [${JSON.stringify(descriptor.id)}, plugin${i}],`),
    ']', '',
    'const ids = new Set<string>()',
    'for (const [expectedId, pluginModule] of entries) {',
    '  const descriptor = harnessDescriptors[expectedId]',
    '  const capabilities = pluginModule?.descriptor?.threadCapabilities',
    '  if (!pluginModule || pluginModule.id !== expectedId || ids.has(pluginModule.id) ||',
    '      pluginModule.descriptor?.id !== expectedId ||',
    '      pluginModule.descriptor.displayName !== descriptor.displayName ||',
    '      !capabilities ||',
    '      capabilities.instructions !== descriptor.threadCapabilities.instructions ||',
    '      capabilities.threadContext !== descriptor.threadCapabilities.threadContext ||',
    '      capabilities.sendContext !== descriptor.threadCapabilities.sendContext ||',
    '      !Array.isArray(capabilities.toolModes) ||',
    '      capabilities.toolModes.length !== descriptor.threadCapabilities.toolModes.length ||',
    '      !descriptor.threadCapabilities.toolModes.every(mode => capabilities.toolModes.includes(mode))) {',
    `    throw new Error(\`Harness ${label} 模块注册不匹配: expected \${expectedId}, actual \${pluginModule?.id}\`)`,
    '  }',
    '  ids.add(pluginModule.id)',
    '}',
    'if (ids.size !== Object.keys(harnessDescriptors).length) {',
    `  throw new Error('Harness ${label} 模块注册集合不完整')`,
    '}', '',
    `export const harness${label}PluginModules: readonly ${type}[] = entries.map(([, module]) => module)`,
    ''
  ]
  return lines.join('\n')
}

// Finish ALL discovery/validation before touching the previous registries.
// Avoid rewriting unchanged output: dev watchers must not rebuild indefinitely.
const outputs = new Map([
  ['harness-registry.ts', shared],
  ['harness-registry.main.ts', processRegistry('main')],
  ['harness-registry.renderer.ts', processRegistry('renderer')]
])
const providerEntries = []
for (const name of Object.keys(desktopPackage.dependencies ?? {}).filter(name => name.startsWith('@openagent/provider-')).sort()) {
  const match = /^@openagent\/provider-([a-z][a-z0-9-]*)$/.exec(name)
  if (!match) throw new Error(`${name}: invalid Provider package name`)
  const root = dirname(require.resolve(`${name}/package.json`))
  const metadata = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  const paths = {}
  for (const entry of ['./manifest', './main']) {
    const exported = metadata.exports?.[entry]
    paths[entry] = artifact(root, name, exported?.default)
    artifact(root, name, exported?.types)
  }
  const { default: descriptor } = await import(pathToFileURL(paths['./manifest']).href)
  if (metadata.name !== name || descriptor?.id !== match[1] || typeof descriptor.displayName !== 'string' ||
    !Array.isArray(descriptor.harnesses) || !descriptor.harnesses.length ||
    descriptor.harnesses.some(target => typeof target.harnessId !== 'string' || typeof target.format !== 'string' ||
      !Array.isArray(target.scopes) || !target.scopes.length || target.scopes.some(scope => !['harness', 'thread'].includes(scope)))) {
    throw new Error(`${name}: invalid Provider descriptor`)
  }
  providerEntries.push({ name, descriptor })
}
outputs.set('provider-registry.main.ts', [header,
  "import type { ProviderPluginModule } from '@openagent/contracts'",
  ...providerEntries.map(({ name }, i) => `import provider${i} from '${name}/main'`),
  `export const providerPluginModules: readonly ProviderPluginModule[] = [${providerEntries.map((_, i) => `provider${i}`).join(', ')}]`,
  `const expected = ${JSON.stringify(providerEntries.map(({ descriptor }) => descriptor))}`,
  'for (const [index, plugin] of providerPluginModules.entries()) {',
  "  if (JSON.stringify(plugin.descriptor) !== JSON.stringify(expected[index])) throw new Error('Provider module registration mismatch')",
  '}', ''
].join('\n'))
const generatedDir = join(desktopRoot, 'src/generated')
mkdirSync(generatedDir, { recursive: true })
for (const [name, content] of outputs) {
  const path = join(generatedDir, name)
  if (!existsSync(path) || readFileSync(path, 'utf8') !== content) writeFileSync(path, content)
}
console.log(`generate-harness-registry: ${[...ids].join(', ')} -> src/generated/harness-registry*.ts`)
